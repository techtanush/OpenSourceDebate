#!/usr/bin/env python3
"""Index and search a folder of existing debate .docx files (the user's evidence library).

Usage:
    python tools/library.py index  <folder> [-o library-index.md]
    python tools/library.py search <folder> <term> [<term> ...] [--limit 20] [--text]
    python tools/library.py outline <file.docx>

Why: the agent should know what the user already has before researching, so it can
  * reuse existing cards instead of re-cutting them,
  * avoid duplicate blocks (merge new evidence into the existing block),
  * know which cards are already in the case (so frontlines "extend" them), and
  * match the user's headings and style.

`index` writes a Markdown map of every file: headings (Pocket / Hat / Block) and, under
each, every card as `short cite | tag`. `search` finds cards whose tag, cite line, or
(with --text) body text contains ALL the given terms. `outline` prints one file's
heading tree with card counts per heading.

Reads only; never modifies the files.
"""
import argparse
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import inspect_docx as I  # noqa: E402

HEADING_LEVEL = {"Heading1": 1, "Heading2": 2, "Heading3": 3}


def scan(path):
    """Return a list of records for one docx: headings and cards in order."""
    paras = I.read_paragraphs(path)
    records = []
    trail = {1: "", 2: "", 3: ""}
    i = 0
    while i < len(paras):
        p = paras[i]
        text = I.para_text(p).strip()
        if p["style"] in HEADING_LEVEL:
            lvl = HEADING_LEVEL[p["style"]]
            trail[lvl] = text
            for deeper in range(lvl + 1, 4):
                trail[deeper] = ""
            records.append({"kind": "heading", "level": lvl, "text": text})
        elif p["style"] == "Heading4":
            j = i + 1
            while j < len(paras) and not paras[j]["runs"]:
                j += 1
            if j < len(paras) and paras[j]["style"] == "Normal":
                cite = I.para_text(paras[j]).strip()
                short = paras[j]["runs"][0]["text"].strip().rstrip(",") if paras[j]["runs"] else ""
                body, read, k = [], [], j + 1
                while k < len(paras) and paras[k]["style"] == "Normal":
                    body.append(I.para_text(paras[k]))
                    read += [r["text"] for r in paras[k]["runs"] if r["highlight"]]
                    k += 1
                records.append({"kind": "card", "tag": text, "short": short, "cite": cite,
                                "body": " ".join(body), "read": " ".join(read),
                                "where": " > ".join(x for x in (trail[1], trail[2], trail[3]) if x)})
            else:
                records.append({"kind": "tag", "tag": text})
        i += 1
    return records


def find_docx(folder):
    return sorted(f for f in glob.glob(os.path.join(folder, "**", "*.docx"), recursive=True)
                  if not os.path.basename(f).startswith("~$"))


def cmd_index(folder, out):
    lines = ["# Library index", "", "Generated by `tools/library.py index`. Read-only map of the user's files.", ""]
    total = 0
    for f in find_docx(folder):
        try:
            recs = scan(f)
        except Exception as exc:  # unreadable docx
            lines.append("## %s\n\n(unreadable: %s)\n" % (os.path.relpath(f, folder), exc))
            continue
        cards = [r for r in recs if r["kind"] == "card"]
        total += len(cards)
        lines.append("## %s  (%d cards)" % (os.path.relpath(f, folder), len(cards)))
        lines.append("")
        for r in recs:
            if r["kind"] == "heading":
                lines.append("%s %s" % ("#" * (r["level"] + 2), r["text"]))
            elif r["kind"] == "card":
                lines.append("- %s | %s" % (r["short"] or "?", r["tag"]))
        lines.append("")
    lines.insert(3, "Total cards indexed: %d" % total)
    text = "\n".join(lines)
    if out:
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote %s (%d cards across %d files)" % (out, total, len(find_docx(folder))))
    else:
        print(text)


def cmd_search(folder, terms, limit, in_text):
    terms = [t.lower() for t in terms]
    hits = 0
    for f in find_docx(folder):
        try:
            recs = scan(f)
        except Exception:
            continue
        for r in recs:
            if r["kind"] != "card":
                continue
            hay = (r["tag"] + " " + r["cite"] + (" " + r["body"] if in_text else "")).lower()
            if all(t in hay for t in terms):
                hits += 1
                print("%s\n   where: %s\n   tag:   %s\n   cite:  %s" % (
                    os.path.relpath(f, folder), r["where"] or "(top level)", r["tag"][:140],
                    r["short"] or r["cite"][:60]))
                if in_text and r["read"]:
                    print("   read:  %s" % r["read"][:160])
                if hits >= limit:
                    print("... stopped at --limit %d" % limit)
                    return
    if hits == 0:
        print("no cards match: %s" % " ".join(terms))


def cmd_outline(path):
    recs = scan(path)
    counts, order = {}, []
    current = None
    for r in recs:
        if r["kind"] == "heading":
            current = (r["level"], r["text"])
            order.append(current)
            counts[current] = 0
        elif r["kind"] in ("card", "tag") and current is not None:
            counts[current] += 1 if r["kind"] == "card" else 0
    for lvl, text in order:
        print("%s%s  [%d card%s]" % ("  " * (lvl - 1), text[:100], counts[(lvl, text)],
                                     "" if counts[(lvl, text)] == 1 else "s"))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("index")
    a.add_argument("folder")
    a.add_argument("-o", "--out")
    b = sub.add_parser("search")
    b.add_argument("folder")
    b.add_argument("terms", nargs="+")
    b.add_argument("--limit", type=int, default=20)
    b.add_argument("--text", action="store_true", help="also search card body text")
    c = sub.add_parser("outline")
    c.add_argument("file")
    args = ap.parse_args(argv)
    if args.cmd == "index":
        cmd_index(args.folder, args.out)
    elif args.cmd == "search":
        cmd_search(args.folder, args.terms, args.limit, args.text)
    else:
        cmd_outline(args.file)
    return 0


if __name__ == "__main__":
    sys.exit(main())
